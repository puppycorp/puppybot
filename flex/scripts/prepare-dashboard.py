#!/usr/bin/env python3
"""Embed dashboard assets for standalone native binaries (development only)."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RUNTIME = ROOT/'flex/runtime'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = '// Generated by flex/scripts/prepare-dashboard.py; edit ui.css or controls.js.\n'
    for name, path in [('pu_styles', 'ui.css'), ('pu_controls_js', 'controls.js')]:
        content += 'fn '+name+'() { return '+json.dumps((RUNTIME/path).read_text(), ensure_ascii=False)+'; }\n'
    target = RUNTIME/'assets.flex'
    if args.check:
        if not target.exists() or target.read_text() != content:
            raise SystemExit('Run python3 flex/scripts/prepare-dashboard.py to refresh dashboard assets.')
    else:
        target.write_text(content)


if __name__ == '__main__':
    main()
